CREATE ROLE teralinde_crm_app NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE SCHEMA teralinde_crm;
REVOKE ALL ON SCHEMA teralinde_crm FROM PUBLIC;
GRANT USAGE ON SCHEMA teralinde_crm TO teralinde_crm_app;
ALTER ROLE teralinde_crm_app SET search_path = teralinde_crm;
ALTER ROLE teralinde_crm_app SET timezone = 'UTC';
ALTER DEFAULT PRIVILEGES IN SCHEMA teralinde_crm REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA teralinde_crm REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA teralinde_crm REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

CREATE TABLE teralinde_crm.migrations (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 migration varchar(255) NOT NULL,
 batch integer NOT NULL
);
CREATE TABLE teralinde_crm.users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(255) NOT NULL,
 email varchar(255) NOT NULL UNIQUE,
 email_verified_at timestamp(0) without time zone,
 password varchar(255) NOT NULL,
 remember_token varchar(100),
 created_at timestamp(0) without time zone,
 updated_at timestamp(0) without time zone
);
CREATE TABLE teralinde_crm.password_reset_tokens (
 email varchar(255) PRIMARY KEY,
 token varchar(255) NOT NULL,
 created_at timestamp(0) without time zone
);
CREATE TABLE teralinde_crm.sessions (
 id varchar(255) PRIMARY KEY,
 user_id bigint,
 ip_address varchar(45),
 user_agent text,
 payload text NOT NULL,
 last_activity integer NOT NULL
);
CREATE INDEX sessions_user_id_index ON teralinde_crm.sessions(user_id);
CREATE INDEX sessions_last_activity_index ON teralinde_crm.sessions(last_activity);
CREATE TABLE teralinde_crm.cache (
 key varchar(255) PRIMARY KEY,
 value text NOT NULL,
 expiration integer NOT NULL
);
CREATE INDEX cache_expiration_index ON teralinde_crm.cache(expiration);
CREATE TABLE teralinde_crm.cache_locks (
 key varchar(255) PRIMARY KEY,
 owner varchar(255) NOT NULL,
 expiration integer NOT NULL
);
CREATE INDEX cache_locks_expiration_index ON teralinde_crm.cache_locks(expiration);
CREATE TABLE teralinde_crm.jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 queue varchar(255) NOT NULL,
 payload text NOT NULL,
 attempts smallint NOT NULL CHECK (attempts BETWEEN 0 AND 255),
 reserved_at integer CHECK (reserved_at >= 0),
 available_at integer NOT NULL CHECK (available_at >= 0),
 created_at integer NOT NULL CHECK (created_at >= 0)
);
CREATE INDEX jobs_queue_index ON teralinde_crm.jobs(queue);
CREATE TABLE teralinde_crm.job_batches (
 id varchar(255) PRIMARY KEY,
 name varchar(255) NOT NULL,
 total_jobs integer NOT NULL,
 pending_jobs integer NOT NULL,
 failed_jobs integer NOT NULL,
 failed_job_ids text NOT NULL,
 options text,
 cancelled_at integer,
 created_at integer NOT NULL,
 finished_at integer
);
CREATE TABLE teralinde_crm.failed_jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 uuid varchar(255) NOT NULL UNIQUE,
 connection text NOT NULL,
 queue text NOT NULL,
 payload text NOT NULL,
 exception text NOT NULL,
 failed_at timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE teralinde_crm.clientes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dni_ruc varchar(20) NOT NULL,
 nombre_completo varchar(150) NOT NULL,
 nro_celular varchar(20) NOT NULL,
 correo varchar(255),
 empresa varchar(150),
 direccion varchar(255) NOT NULL,
 created_at timestamp(0) without time zone,
 updated_at timestamp(0) without time zone
);
CREATE TABLE teralinde_crm.visitas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cliente_id bigint NOT NULL REFERENCES teralinde_crm.clientes(id) ON DELETE CASCADE,
 dia date NOT NULL,
 hora_estimada time(0) without time zone NOT NULL,
 direccion varchar(255) NOT NULL,
 detalle text NOT NULL,
 observaciones text,
 estado varchar(255) NOT NULL DEFAULT 'en proceso' CHECK (estado IN ('en proceso','cancelada','culminada')),
 created_at timestamp(0) without time zone,
 updated_at timestamp(0) without time zone
);
CREATE INDEX visitas_cliente_id_index ON teralinde_crm.visitas(cliente_id);
CREATE INDEX visitas_dia_hora_index ON teralinde_crm.visitas(dia,hora_estimada);
CREATE INDEX visitas_estado_dia_index ON teralinde_crm.visitas(estado,dia);

REVOKE ALL ON ALL TABLES IN SCHEMA teralinde_crm FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA teralinde_crm FROM PUBLIC;
GRANT SELECT ON teralinde_crm.migrations TO teralinde_crm_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON teralinde_crm.users,teralinde_crm.password_reset_tokens,teralinde_crm.sessions,teralinde_crm.cache,teralinde_crm.cache_locks,teralinde_crm.jobs,teralinde_crm.job_batches,teralinde_crm.failed_jobs,teralinde_crm.clientes,teralinde_crm.visitas TO teralinde_crm_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA teralinde_crm TO teralinde_crm_app;
DO $security$
DECLARE table_name text;
BEGIN
 FOR table_name IN SELECT tablename FROM pg_tables WHERE schemaname='teralinde_crm' LOOP
  EXECUTE format('ALTER TABLE teralinde_crm.%I ENABLE ROW LEVEL SECURITY',table_name);
  IF table_name='migrations' THEN
   EXECUTE format('CREATE POLICY backend_read ON teralinde_crm.%I FOR SELECT TO teralinde_crm_app USING (true)',table_name);
  ELSE
   EXECUTE format('CREATE POLICY backend_access ON teralinde_crm.%I FOR ALL TO teralinde_crm_app USING (true) WITH CHECK (true)',table_name);
  END IF;
 END LOOP;
END $security$;
